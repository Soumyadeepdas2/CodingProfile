class Solution {
  public:
    void isInRange(int n) {
        // you don't need to take input
        // here just write code which print correct answer according to n
        if(n==1){
            cout<<"one"<<endl;
        }else if(n==2){
            cout<<"two"<<endl;
        }
        else if(n==3){
            cout<<"three"<<endl;
        }else if(n==4){
            cout<<"four"<<endl;
        }else if(n==5){
            cout<<"five"<<endl;
        }else if(n==6){
            cout<<"six"<<endl;
        }else if(n==7){
            cout<<"seven"<<endl;
        }else if(n==8){
            cout<<"eight"<<endl;
        }else if(n==9){
            cout<<"nine"<<endl;
        }else if(n==10){
            cout<<"ten"<<endl;
        }else{
            cout<<"not in range"<<endl;
        }
    }
};